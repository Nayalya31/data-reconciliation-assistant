# На публичных страницах порядок списка — порядок портфолио.
CASES = [ASSISTANT, MANICURE_ASSISTANT, SAFETY_BRIEFING, DATA_RECONCILIATION]


def get_case(slug: str):
    """Возвращает только опубликованный кейс."""
    for case in CASES:
        if case["slug"] == slug:
            return case
    return None


def is_draft_case(slug: str) -> bool:
    """Помогает сохранить старые адреса без публикации демонстрационных материалов."""
    return any(case["slug"] == slug for case in DRAFT_CASES)


def get_neighbors(slug: str):
    """Предыдущий и следующий опубликованные кейсы для будущего расширения портфолио."""
    for index, case in enumerate(CASES):
        if case["slug"] == slug:
            previous = CASES[index - 1] if index else None
            following = CASES[index + 1] if index + 1 < len(CASES) else None
            return previous, following
    return None, None
